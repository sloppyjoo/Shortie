import AppKit
import Carbon.HIToolbox
import Observation

/// One thing you copied.
nonisolated struct ClipboardEntry: Codable, Identifiable, Hashable {
    enum Content: Codable, Hashable {
        case text(String)
        /// Saved as a PNG in the clipboard folder.
        case image(fileName: String)
        case files(paths: [String])
    }

    var id = UUID()
    var content: Content
    var date = Date()
    /// The app that was in front when you copied it.
    var sourceBundleID: String?
    var isPinned = false

    /// Words to match when searching.
    var searchText: String {
        switch content {
        case .text(let text): text
        case .image: "image picture"
        case .files(let paths): paths.map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        }
    }
}

/// Remembers what you copy, so you can paste it again later.
///
/// macOS has no "clipboard changed" notification, so like every clipboard
/// manager we check its change counter twice a second, which costs almost
/// nothing. History is saved in BestTouchTool's folder on your Mac and never
/// sent anywhere.
///
/// Passwords are never kept: password managers label them "concealed" (an
/// open standard, nspasteboard.org), and copies made in apps you exclude are
/// ignored too.
@Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    private(set) var entries: [ClipboardEntry] = []

    /// Apps whose copies are never kept. Starts with the common password managers.
    static let defaultExcludedApps = ["com.1password.1password", "com.bitwarden.desktop", "com.apple.Passwords"]

    var isEnabled: Bool { UserDefaults.standard.object(forKey: DefaultsKey.clipboardEnabled) as? Bool ?? true }
    private var limit: Int { UserDefaults.standard.object(forKey: DefaultsKey.clipboardLimit) as? Int ?? 100 }
    var excludedApps: [String] {
        UserDefaults.standard.stringArray(forKey: DefaultsKey.clipboardExcludedApps) ?? Self.defaultExcludedApps
    }

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let thumbnails = NSCache<NSString, NSImage>()
    @ObservationIgnored private let folder: URL
    @ObservationIgnored private let imagesFolder: URL

    /// Labels that say "don't keep this" (nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    private init() {
        folder = URL.applicationSupportDirectory.appending(path: "BestTouchTool", directoryHint: .isDirectory)
        imagesFolder = folder.appending(path: "Clipboard Images", directoryHint: .isDirectory)
        try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: fileURL),
           let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) {
            entries = saved
        }
    }

    private var fileURL: URL { folder.appending(path: "clipboard.json") }

    func start() {
        guard timer == nil else { return }
        addShortcutOnce()
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistory.shared.check() }
        }
        // Let macOS fold this check in with other wake-ups, which saves battery.
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// The first time, give clipboard history its shortcut: Hyper + V.
    private func addShortcutOnce() {
        let defaults = UserDefaults.standard
        guard !defaults.bool(forKey: DefaultsKey.clipboardShortcutAdded) else { return }
        defaults.set(true, forKey: DefaultsKey.clipboardShortcutAdded)
        let hyperV = KeyCombo(keyCode: UInt16(kVK_ANSI_V), modifiers: [.control, .option, .shift, .command], keyName: "V")
        ShortcutStore.shared.shortcuts.append(Shortcut(keyCombo: hyperV, action: .system(action: .clipboardHistory)))
    }

    // MARK: - Remembering

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard isEnabled else { return }
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, excludedApps.contains(source) { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            remember(.files(paths: urls.map(\.path)), from: source)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            remember(.text(text), from: source)
        } else if let image = NSImage(pasteboard: pasteboard), let png = Self.png(from: image), png.count < 15_000_000 {
            let fileName = UUID().uuidString + ".png"
            try? png.write(to: imagesFolder.appending(path: fileName))
            remember(.image(fileName: fileName), from: source)
        }
    }

    private func remember(_ content: ClipboardEntry.Content, from source: String?) {
        // Copying the same thing again moves it back to the top.
        if let index = entries.firstIndex(where: { $0.content == content }) {
            var entry = entries.remove(at: index)
            entry.date = Date()
            entries.insert(entry, at: 0)
        } else {
            entries.insert(ClipboardEntry(content: content, sourceBundleID: source), at: 0)
        }
        trimToLimit()
        save()
    }

    /// Keeps your pinned items, plus the newest unpinned ones up to the limit.
    private func trimToLimit() {
        var unpinnedSeen = 0
        var kept: [ClipboardEntry] = []
        for entry in entries {
            if entry.isPinned {
                kept.append(entry)
            } else if unpinnedSeen < limit {
                unpinnedSeen += 1
                kept.append(entry)
            } else {
                deleteFiles(of: entry)
            }
        }
        entries = kept
    }

    // MARK: - Using it

    /// Puts an entry back on the clipboard and pastes it into the app in front.
    func paste(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let fileName):
            if let image = NSImage(contentsOf: imagesFolder.appending(path: fileName)) {
                pasteboard.writeObjects([image])
            }
        case .files(let paths):
            pasteboard.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
        }
        // That copy was us: don't record it again, just move the entry to the top.
        lastChangeCount = pasteboard.changeCount
        if let index = entries.firstIndex(where: { $0.id == entry.id }) {
            var moved = entries.remove(at: index)
            moved.date = Date()
            entries.insert(moved, at: 0)
            save()
        }

        // Give the panel a moment to close and the app to be in front again.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            KeyPresser.press(KeyCombo(keyCode: UInt16(kVK_ANSI_V), modifiers: .command, keyName: "V"))
        }
    }

    func togglePin(_ entry: ClipboardEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        save()
    }

    func delete(_ entry: ClipboardEntry) {
        deleteFiles(of: entry)
        entries.removeAll { $0.id == entry.id }
        save()
    }

    /// Clears everything except pinned items.
    func clearUnpinned() {
        entries.filter { !$0.isPinned }.forEach(deleteFiles)
        entries.removeAll { !$0.isPinned }
        save()
    }

    /// A small preview of a copied image, for the list. Previews are made once
    /// and cached; macOS frees the cache by itself if memory gets tight.
    func image(for fileName: String) -> NSImage? {
        if let cached = thumbnails.object(forKey: fileName as NSString) { return cached }
        let url = imagesFolder.appending(path: fileName)
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
        else { return nil }
        let image = NSImage(cgImage: thumbnail, size: .zero)
        thumbnails.setObject(image, forKey: fileName as NSString)
        return image
    }

    // MARK: - Storage

    private func deleteFiles(of entry: ClipboardEntry) {
        if case .image(let fileName) = entry.content {
            thumbnails.removeObject(forKey: fileName as NSString)
            try? FileManager.default.removeItem(at: imagesFolder.appending(path: fileName))
        }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: fileURL, options: [.atomic, .completeFileProtection])
    }

    private static func png(from image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
