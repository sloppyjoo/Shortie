import AppKit

/// Makes one key act as another, at the keyboard-driver level (macOS's `hidutil`),
/// so it works everywhere, even at the login window. Remappings last until you
/// reset them or Shortie quits. The Hyper key's Caps Lock remapping lives here too,
/// because `hidutil` keeps a single list for everything.
enum KeyRemapper {
    /// Remappings made by actions, as hardware key numbers.
    private static var remaps: [(from: Int, to: Int)] = []

    static func remap(from: UInt16, to: UInt16) {
        guard let source = usage(for: from), let destination = usage(for: to) else {
            NSSound.beep()
            return
        }
        remaps.removeAll { $0.from == source }
        if source != destination { remaps.append((source, destination)) }
        write()
        HUD.show("\(name(for: from)) → \(name(for: to))", systemImage: "keyboard")
    }

    /// Whether some key has been made to act as Hyper (by remapping it to F18).
    static var usesHyper: Bool {
        remaps.contains { $0.to == 0x7_0000_006D }
    }

    static func reset() {
        remaps.removeAll()
        write()
        HUD.show("Keys Back to Normal", systemImage: "keyboard")
    }

    /// Clears every remapping, for when Shortie quits.
    static func clearAll() {
        remaps.removeAll()
        write(hyper: false)
    }

    /// Sends the full list to the keyboard driver.
    static func write(hyper: Bool? = nil) {
        // Caps Lock becomes F18, which Shortie turns into Hyper.
        let capsLock = 0x7_0000_0039
        let f18 = 0x7_0000_006D
        var pairs = remaps.map { ($0.from, $0.to) }
        if hyper ?? HyperKey.shared.isEnabled {
            pairs.removeAll { $0.0 == capsLock }
            pairs.append((capsLock, f18))
        }
        let list = pairs.map { #"{"HIDKeyboardModifierMappingSrc":\#($0.0),"HIDKeyboardModifierMappingDst":\#($0.1)}"# }
        let mapping = #"{"UserKeyMapping":[\#(list.joined(separator: ","))]}"#
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/hidutil")
        process.arguments = ["property", "--set", mapping]
        process.standardOutput = FileHandle.nullDevice
        try? process.run()
        process.waitUntilExit()
    }

    /// Every key that can be remapped, by the key code macOS uses for it.
    static let keyCodes: [UInt16] = usages.keys.sorted { name(for: $0).localizedStandardCompare(name(for: $1)) == .orderedAscending }

    /// Its name, as printed on a US keyboard.
    nonisolated static func name(for keyCode: UInt16) -> String {
        names[keyCode] ?? "Key \(keyCode)"
    }

